export function getTranslation(key, lang = "de", params = {}) {
  const selectedLang = TRANSLATIONS[lang] ? lang : "de";
  let template = TRANSLATIONS[selectedLang]?.[key] ?? TRANSLATIONS.de[key] ?? key;
  if (typeof template === "string") {
    for (const [k, v] of Object.entries(params)) {
      template = template.replaceAll(`{${k}}`, String(v));
    }
  }
  return template;
}

export function t(key, params = {}, lang = "de") {
  return getTranslation(key, lang, params);
}
